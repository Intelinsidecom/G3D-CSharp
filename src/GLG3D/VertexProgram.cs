using System;
using System.IO;
using G3D;

namespace G3D
{

    /**
      Reference-counted smart pointer to VertexProgram.
    */
    // typedef ReferenceCountedPointer<class VertexProgram> VertexProgramRef;

    /**
      Abstraction of OpenGL vertex programs.  This class can be used with raw OpenGL,
      without RenderDevice or SDL.

      If you use VertexProgramRef instead of VertexProgram*, the texture memory will be
      garbage collected.

      The vertex program must be written in the vertex program <B>assembly languages</B>
      specified by either:

        http://oss.sgi.com/projects/ogl-sample/registry/ARB/vertex_program.txt

        http://oss.sgi.com/projects/ogl-sample/registry/NV/vertex_program2.txt

      You can also write your programs in the NVIDIA Cg language and compile them with
      cgc to assembly language.  You cannot load Cg programs directly with a VertexProgram.

      If an error is encountered inside a shader in debug mode, that error is printed to the
      debug window (under MSVC) and the programmer can fix the error and reload the
      shader without reloading the program.

      See G3D::GPUProgram for information on how constants and variable assignments
      generated by the Cg compiler are handled.

      @deprecated
      Use G3D::VertexShader
     */
    public sealed class VertexProgram : GPUProgram
    {
        private const string DefaultPixelSource = "void main() { gl_FragColor = vec4(0.0, 0.0, 0.0, 1.0); }";

        private VertexProgram(string name, string filename) : base(name, filename)
        {
            vertexStage = true;
        }

        public static VertexProgram fromFile(string filename)
        {
            return fromFile(filename, filename, null);
        }

        public static VertexProgram fromFile(string name, string filename)
        {
            return fromFile(name, filename, null);
        }

        public static VertexProgram fromFile(string name, string filename, GPUProgram.Settings settings)
        {
            string source = File.ReadAllText(filename);
            return fromSource(name, source, settings, filename);
        }

        public static VertexProgram fromCode(string name, string code)
        {
            return fromSource(name, code, null, "");
        }

        public static VertexProgram fromSource(string name, string source)
        {
            return fromSource(name, source, null, "");
        }

        public static VertexProgram fromSource(string name, string source, GPUProgram.Settings settings)
        {
            return fromSource(name, source, settings, "");
        }

        private static VertexProgram fromSource(string name, string source, GPUProgram.Settings settings, string filename)
        {
            VertexProgram program = new VertexProgram(name, filename);
            string defines = settings == null ? "" : settings.defines;
            program.compileProgram(GraphicsShaderLanguage.GLSL, defines + source, DefaultPixelSource);
            return program;
        }
    }
}
