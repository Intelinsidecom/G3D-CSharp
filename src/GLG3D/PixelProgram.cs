using System;
using System.IO;
using G3D;

namespace G3D
{

    /**
      Reference-counted smart pointer to PixelProgram.
    */
    // typedef ReferenceCountedPointer<class PixelProgram> PixelProgramRef;

    /**
      Abstraction of OpenGL pixel programs.  This class can be used with raw OpenGL,
      without RenderDevice or SDL.

      If you use PixelProgramRef instead of PixelProgram*, the texture memory will be
      garbage collected.

      The vertex program must be written in the ARB pixel program assembly language
      specified by:
      http://oss.sgi.com/projects/ogl-sample/registry/ARB/fragment_program.txt

      If an error is encountered inside a shader in debug mode, that error is printed to the
      debug window (under MSVC) and the programmer can fix the error and reload the
      shader without reloading the program.

      See G3D::GPUProgram for information on how constants generated by the Cg compiler
      are handled.
      @deprecated
      Use G3D::PixelShader
     */
    public sealed class PixelProgram : GPUProgram
    {
        private const string DefaultVertexSource = "void main() { gl_Position = gl_Vertex; }";

        private PixelProgram(string name, string filename) : base(name, filename)
        {
            vertexStage = false;
        }

        public static PixelProgram fromFile(string filename)
        {
            return fromFile(filename, filename, null);
        }

        public static PixelProgram fromFile(string name, string filename)
        {
            return fromFile(name, filename, null);
        }

        public static PixelProgram fromFile(string name, string filename, GPUProgram.Settings settings)
        {
            string source = File.ReadAllText(filename);
            return fromSource(name, source, settings, filename);
        }

        public static PixelProgram fromCode(string name, string code)
        {
            return fromSource(name, code, null, "");
        }

        public static PixelProgram fromSource(string name, string source)
        {
            return fromSource(name, source, null, "");
        }

        public static PixelProgram fromSource(string name, string source, GPUProgram.Settings settings)
        {
            return fromSource(name, source, settings, "");
        }

        private static PixelProgram fromSource(string name, string source, GPUProgram.Settings settings, string filename)
        {
            PixelProgram program = new PixelProgram(name, filename);
            string defines = settings == null ? "" : settings.defines;
            string code = defines + source;

            int assemblyUnit;
            GPUProgram.Extension assemblyExtension;
            if (isAssemblyCode(code, out assemblyUnit, out assemblyExtension))
            {
                program.loadAssemblyProgram(code);
                return program;
            }

            program.compileProgram(GraphicsShaderLanguage.GLSL, DefaultVertexSource, code);
            return program;
        }
    }
}
